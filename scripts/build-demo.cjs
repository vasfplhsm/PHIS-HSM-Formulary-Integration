// Refresh the offline demo snapshot and settings sandbox from the actual extension.
const fs = require('node:fs'); const path = require('node:path');
const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'extension/manifest.json'), 'utf8'));
const formulary = fs.readFileSync(path.join(root, 'extension/data/formulary.json'), 'utf8').trim();
fs.mkdirSync(path.join(root, 'demo/data'), {recursive: true});
fs.writeFileSync(path.join(root, 'demo/data/formulary.js'), '/* Generated by scripts/build-demo.cjs; source: extension/data/formulary.json */\nglobalThis.PhisDemoBuild = ' + JSON.stringify({version: manifest.version}) + ';\nglobalThis.PhisDemoFormulary = ' + formulary + ';\n');
let html = fs.readFileSync(path.join(root, 'extension/settings.html'), 'utf8')
 .replace('<html lang="en">', '<html lang="en" data-phis-demo="true" data-phis-demo-view="settings">')
 .replace('href="settings.css"', 'href="../extension/settings.css"')
 .replace('href="settings.html"', 'href="settings-preview.html"')
 .replace('<main>', '<main><p class="notice">SETTINGS SANDBOX — changes are in memory in this page only. Permission prompts are simulated; nothing changes in the installed extension or PHIS. Reloading resets this sandbox.</p>')
 .replace('<script src="csv.js"></script>', '<script src="data/formulary.js"></script><script src="scenarios.js"></script><script src="adapter.js"></script>\n  <script src="../extension/csv.js"></script>')
 .replace(/src="(matcher|checks|settings)\.js"/g, 'src="../extension/$1.js"');
fs.writeFileSync(path.join(root, 'demo/settings-preview.html'), '<!-- Generated by scripts/build-demo.cjs -->\n' + html);
console.log('Offline formulary and settings sandbox generated for version ' + manifest.version);
// A single HTML entry point avoids local-file requests for data, scripts, or styles.
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const inline = code => code.replace(/<\/script/gi, '<\\/script');
let standalone = read('demo/index.html')
 .replace('<link rel="stylesheet" href="demo.css">', '<style>' + read('demo/demo.css') + '\n' + read('extension/content.css') + '</style>')
 .replace('href="settings-preview.html"', 'href="demo/settings-preview.html"');
standalone = standalone.replace(/<script src="([^"]+)"><\/script>/g, (tag, filename) => {
 if (filename !== 'preview.js') return '<script>\n' + inline(read('demo/' + filename)) + '\n</script>';
 let scripts = '<script>window.PhisDemoBundled = true;</script>\n';
 for (const file of ['matcher.js','checks.js','prescription.js','content.js']) scripts += '<script>if (window.PhisDemoBackend) {\n' + inline(read('extension/' + file)) + '\n}</script>\n';
 return scripts + '<script>\n' + inline(read('demo/preview.js')) + '\n</script>';
});
fs.writeFileSync(path.join(root, 'OPEN-DEMO.html'), '<!-- Generated by scripts/build-demo.cjs; demo only, no external runtime assets. -->\n' + standalone);
console.log('Self-contained OPEN-DEMO.html generated.');
